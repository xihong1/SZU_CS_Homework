/**
  ******************************************************************************
  * @file    debug_led.h
  * @brief   LED 接线自检 (调试用)
  *
  * 逐个驱动 PB0 / PB1 / PA7 / PA8, 每个引脚拉低 3 秒、拉高 3 秒,
  * 同时在 OLED 上显示当前正在驱动哪个引脚。
  *
  * 用途: 接线/极性不明时, 用来确定
  *         1) 哪颗物理灯对应哪个引脚
  *         2) 是高电平点亮还是低电平点亮
  *       这是做任务三(三色呼吸灯)的前提 —— 极性搞反的话, PWM 占空比
  *       调出来的效果会正好相反(越亮越暗)。
  *
  * 注意: PB0/PB1 同时也是板载 DS1(绿)/DS0(红) 的引脚, 那两个灯是焊死的,
  *       不受外接杜邦线影响, 可以拿来交叉验证。
  ******************************************************************************
  */

#ifndef __DEBUG_LED_H
#define __DEBUG_LED_H

/* 进入 LED 自检, 内部是死循环, 不会返回 */
void debug_led_run(void);

#endif /* __DEBUG_LED_H */
