/**
  ******************************************************************************
  * @file    gtim_ic.h
  * @brief   通用定时器输入捕获 —— TIM1_CH1 (PA8), PWM 输入模式
  *
  * 接线:  PB1 (TIM3_CH4, PWM 输出)  ──跳线──  PA8 (TIM1_CH1, 捕获输入)
  *
  * 说明: 开发指南的输入捕获例子用的是 TIM5_CH1/PA0, 但本板实测 PA0 与排针上
  *       实际可接的位置对不上; 换到 PA1(TIM5_CH2) 后从模式触发又始终把计数器
  *       压在 0, 排查成本很高。
  *       PA8 是确定引出的引脚(上面接着 LED), TIM1_CH1 是标准 AF1, 最稳妥。
  *
  * PWM 输入模式是 STM32 用来"一个通道同时测周期和占空比"的硬件技巧:
  *     TI1 的信号同时接到 IC1 和 IC2 两个捕获通道
  *     IC1 捕上升沿, 并把计数器清零(从模式复位)
  *     IC2 捕下降沿
  * 于是:
  *     CCR1 = 一个完整周期的计数     -> 频率 = 计数时钟 / CCR1
  *     CCR2 = 高电平部分的计数       -> 占空比 = CCR2 / CCR1
  *
  * 关键配置 (直接操作寄存器, 因为这几个位在 HAL 里分散在多处, 直写更清楚):
  *     CCMR1: CC1S=01 (IC1 映射到 TI1), CC2S=10 (IC2 也映射到 TI1)
  *     CCER : CC1E=1(使能), CC2E=1(使能), CC2P=1(下降沿)
  *     SMCR : TS=TI1FP1, SMS=100(复位模式) —— 上升沿到来时把 CNT 清零
  *
  * 计数时钟取 10 MHz (PSC=8), 即分辨率 0.1 us。
  * 这一点很重要: 10 kHz 的信号周期只有 100 us, 若用 1 MHz 计数就只有
  * 100 个计数, 量化误差 1%; 用 10 MHz 则降到 0.1%。
  ******************************************************************************
  */

#ifndef __GTIM_IC_H
#define __GTIM_IC_H

#include "stm32f4xx_hal.h"

/* 捕获计数时钟: 180 MHz / (PSC+1) = 180 MHz / 36 = 5 MHz
 * (TIM1 是 16 位, 时钟不能取太高, 否则 100 Hz 的周期会溢出) */
#define GTIM_IC_CLK_HZ      5000000UL

void     gtim_ic_init(void);

/**
  * @brief  读一次测量结果
  * @param  period : 输出, 一个周期的计数 (CCR1)
  * @param  high   : 输出, 高电平的计数 (CCR2)
  * @return 1 = 数据有效, 0 = 数据无效(还没捕到 / 正在翻新)
  *
  * 连续读两次 CCR1, 只有两次一致才认为数据稳定, 避免读到跨周期错配的
  * 周期/高电平组合(它们在硬件上是两个独立的寄存器, 不在同一时刻锁存)。
  */
uint8_t  gtim_ic_read(uint32_t *period, uint32_t *high);

#endif /* __GTIM_IC_H */
