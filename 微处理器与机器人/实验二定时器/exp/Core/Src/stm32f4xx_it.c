/**
  ******************************************************************************
  * @file    stm32f4xx_it.c
  * @brief   中断服务程序
  *
  * 每个外设的中断处理函数都只做"计数 + 置标志"这类极短的工作,
  * 具体处理放到主循环里, 避免在高频中断中做耗时操作
  * (实验要求明确写了: 显示刷新和串口输出不得放入高频定时器中断)。
  ******************************************************************************
  */

#include "stm32f4xx_hal.h"
#include "tick.h"
#include "gtim_ic.h"

/* 定义于 main.c, 供 SWD 回读 */
extern volatile uint32_t g_dbg_systick_cnt;
extern volatile uint32_t g_fault_flags;

/* ==========================================================================
 * Cortex-M4 内核异常
 * ========================================================================== */

/**
  * @brief  SysTick 中断: HAL 的 1 ms 时基
  *         必须调用 HAL_IncTick() 让 uwTick 累加, 否则 HAL_Delay 会死等。
  */
void SysTick_Handler(void)
{
  HAL_IncTick();
  g_dbg_systick_cnt++;
}

/**
  * @brief  硬件错误: 记录标志位后停机。
  *         调试时用 pyOCD 读 g_fault_flags 就能知道是哪种错误。
  */
void HardFault_Handler(void)
{
  g_fault_flags = 0x1U;   /* 1 = HardFault */
  while (1) { }
}

/* ==========================================================================
 * 外设中断
 * ========================================================================== */

/**
  * @brief  TIM6 更新中断 —— 1 ms 系统时间基准
  *
  * TIM6 和 DAC 共用这个中断向量, 这里只用到 TIM6。
  * 处理体全部丢给 tick_isr(), 里面只做计数和置标志, 保证中断极短。
  */
void TIM6_DAC_IRQHandler(void)
{
  tick_isr();
}

/* 说明: 任务四的输入捕获**故意不使用中断**。
 * 每个上升沿都进一次中断会带来中断风暴的风险(实测 10 kHz 信号下 CPU 会被
 * 一直困在中断里, 连初始化都走不完)。改用轮询 TIM5->CNT 判断信号有无,
 * 详见 gtim_ic_signal_alive()。 */
