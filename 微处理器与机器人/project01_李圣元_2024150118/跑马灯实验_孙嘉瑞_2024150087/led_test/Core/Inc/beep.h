/**
 ******************************************************************************
 * @file    beep.h
 * @brief   板载蜂鸣器控制（跑马灯实验：每次有效按键响一声）
 *
 *  硬件说明（阿波罗 F429）：
 *    板载蜂鸣器不是直接接在 MCU 引脚上的，而是接在 PCF8574 这颗 I2C 扩展芯片的
 *    P0 脚上。所以要响，必须通过 I2C 给 PCF8574 写数据（写 0 到 P0）。
 *
 *    板上的 I2C 总线（和 24C02 存储芯片共用）：
 *        PH4 = IIC_SCL
 *        PH5 = IIC_SDA
 *    PCF8574 的地址线 A0~A2 都接地，所以 7 位地址是 0x20（写地址 0x40）。
 *
 *  这里用“软件模拟 I2C 时序”的办法驱动（和正点原子例程一致）：
 *    两根普通 IO 口按 I2C 协议手动翻转电平，不需要占用硬件 I2C 外设，
 *    也不会跟其它用到 I2C 的模块抢资源。
 ******************************************************************************
 */
#ifndef __BEEP_H
#define __BEEP_H

#include "main.h"

/* P0 输出 0 = 蜂鸣器响。若实测相反（一直响 / 按键时反而不响），改成 1 即可 */
#define BEEP_ON_LEVEL       0

#define BEEP_DEFAULT_MS     80      /* 按键提示音时长：80ms */

void beep_init(void);
void beep_start(uint16_t ms);       /* 让蜂鸣器开始响，ms 毫秒后自动关闭 */
void beep_task(void);               /* 需要在主循环里反复调用 */

#endif /* __BEEP_H */
